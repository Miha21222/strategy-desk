// Regenerates src/i18n_ru.rs from the TS desk's dictionary
// (src/renderer/i18n/ru.ts), keeping only the sections the Rust desk shows.
//
//   node --experimental-strip-types rust/crates/desk-ui/tools/gen-i18n.mjs
//
// Run from the repository root. The TS file stays the source of truth until
// the Electron app is removed (TZ stage 8).
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const KEEP = ['app', 'tabs', 'macro', 'sidebar'];
const src = 'src/renderer/i18n/ru.ts';
const out = 'rust/crates/desk-ui/src/i18n_ru.rs';

const tmp = '/tmp/desk-ru.mts';
writeFileSync(tmp, readFileSync(src, 'utf8'));
const { ru } = await import(pathToFileURL(tmp).href);

const rows = [];
const walk = (node, path) => {
  for (const [k, v] of Object.entries(node)) {
    const key = path ? `${path}.${k}` : k;
    if (typeof v === 'string') rows.push([key, v]);
    else if (v && typeof v === 'object' && !Array.isArray(v)) walk(v, key);
  }
};
for (const s of KEEP) walk({ [s]: ru[s] }, '');
// Sorted by key (ASCII), so the lookup can binary-search.
rows.sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0));

const lit = (s) => JSON.stringify(s).replace(/\\u([0-9a-fA-F]{4})/g, '\\u{$1}');
const body = rows.map(([k, v]) => `    (${lit(k)}, ${lit(v)}),`).join('\n');
writeFileSync(
  out,
  `// @generated by tools/gen-i18n.mjs from src/renderer/i18n/ru.ts — do not edit by hand.\n` +
    `// Sections: ${KEEP.join(', ')}. ${rows.length} strings.\n\n` +
    `#[rustfmt::skip]\npub(crate) static RU_TS: &[(&str, &str)] = &[\n${body}\n];\n`,
);
console.log(`${rows.length} strings → ${out}`);
