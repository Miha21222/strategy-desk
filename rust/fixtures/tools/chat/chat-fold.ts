// What the OLD app made of a stream-json conversation — the reference for the
// Rust chat (TEAM.md rule 4: Rust is checked against the old behaviour, not
// against itself).
//
//   node chat-fold.cjs <repo_root> <out_dir>      (built by capture-chat.sh)
//
// The stream goes through the old code for real:
//   stdout line → JSON.parse, non-JSON skipped   (the Agent SDK's transport: «Non-JSON stdout» → continue)
//             → drivers/claude.ts `translate`    (SDKMessage → DriverEvent)  — executed
//             → agent.ts `startChat`             (busy check, retry after a crash, transcript,
//                                                 session id, token and cost tally, `done`) — executed,
//                                                 with store / runtime / resources stubbed in memory
//             → app.tsx `chat:event` handler     (what the screen shows)     — transcribed below
//                                                 line for line (a Preact effect cannot be called alone)
// Only the process is replaced: a replay driver feeds the recorded lines and,
// where the case says so, presses «Стоп» or throws the SDK's exit error.
