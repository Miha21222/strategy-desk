const PROMPTS: Record<string, string> = {
  'prompt/macro-review.md': readFileSync(path.join(root, 'prompt', 'macro-review.md'), 'utf8').trim(),
  'prompt/ask.md': readFileSync(path.join(root, 'prompt', 'ask.md'), 'utf8').trim(),
};
const promptFile = (sp: string) => Object.keys(PROMPTS).find((k) => sp.startsWith(PROMPTS[k])) ?? null;
const hash = (s: string) => createHash('sha256').update(s).digest('hex');

/** A screen message without the clock: `live` instead of `at === -1`. */
function screenItem(m: Msg): Record<string, unknown> {
  if (m.role === 'assistant') return { role: 'assistant', text: m.text, live: m.at === -1, thinking: m.thinking, tools: m.tools.map((x) => ({ id: x.id, name: x.name, input: x.input, ok: x.ok, result: x.result })) };
  if (m.role === 'notice') return { role: 'notice', level: m.level, text: m.text };
  return { role: 'user', text: m.text };
}

function summarize(items: Record<string, unknown>[]): unknown {
  return items.map((m) => (typeof m.text === 'string' && (m.text as string).length > 400 ? { ...m, text: { chars: [...(m.text as string)].length, utf16: (m.text as string).length, sha256: hash(m.text as string), head: (m.text as string).slice(0, 80), tail: (m.text as string).slice(-80) }, tools: Array.isArray(m.tools) ? { count: (m.tools as unknown[]).length, ok: (m.tools as { ok: unknown }[]).filter((x) => x.ok === true).length, first: (m.tools as unknown[])[0] ?? null } : m.tools } : m));
}

