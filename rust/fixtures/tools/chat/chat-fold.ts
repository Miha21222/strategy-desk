// ------------------------------------------------------------ the replay driver

interface Attempt {
  stream: string;
  /** Press «Стоп» (agent.ts stopChat) right before this line index. */
  stopBefore?: number;
  /** Throw this after the lines, the way the SDK ends a dead process's turn. */
  exit?: string;
  /** Wait here until `release()` — lets a second Send arrive while busy. */
  holdAt?: number;
}

const streamPath = (name: string) => (path.isAbsolute(name) ? name : path.join(STREAMS, name));
const lines = (name: string) => readFileSync(streamPath(name), 'utf8').split('\n').filter((l) => l.trim() !== '');
const sha = (name: string) => createHash('sha256').update(readFileSync(streamPath(name))).digest('hex');

/**
 * The 10 000-line stream is not committed (it would be megabytes of noise): it
 * is generated by this rule, which the Rust test repeats byte for byte (the
 * expected file carries the rule and the sha256 of its output).
 */
export const SYNTH_10K = {
  lines: 10000,
  rule: [
    'line 1: {"type":"system","subtype":"init","session_id":"qa-10k","model":"claude-fake","claude_code_version":"0.0.0-qa","tools":["Bash"],"mcp_servers":[]}',
    'then for i in 0..10000: if i % 50 == 49 two lines:',
    '  {"type":"assistant","message":{"content":[{"type":"tool_use","id":"toolu_<i>","name":"Bash","input":{"command":"echo <i>"}}]},"parent_tool_use_id":null,"session_id":"qa-10k"}',
    '  {"type":"user","message":{"content":[{"type":"tool_result","tool_use_id":"toolu_<i>","content":"<i>","is_error":<i % 500 == 499>}]},"parent_tool_use_id":null,"session_id":"qa-10k"}',
    '  else one line: {"type":"stream_event","event":{"type":"content_block_delta","index":0,"delta":{"type":"text_delta","text":"w<i> "}},"parent_tool_use_id":null,"session_id":"qa-10k"}',
    'last: {"type":"result","subtype":"success","is_error":false,"num_turns":1,"session_id":"qa-10k","total_cost_usd":1.2345,"usage":{"input_tokens":1000,"output_tokens":10000}}',
    'every line ends with \\n (LF), UTF-8, no BOM',
  ],
};
function synth10k(): string {
  const out = ['{"type":"system","subtype":"init","session_id":"qa-10k","model":"claude-fake","claude_code_version":"0.0.0-qa","tools":["Bash"],"mcp_servers":[]}'];
  for (let i = 0; i < SYNTH_10K.lines; i++) {
    if (i % 50 === 49) {
      out.push(`{"type":"assistant","message":{"content":[{"type":"tool_use","id":"toolu_${i}","name":"Bash","input":{"command":"echo ${i}"}}]},"parent_tool_use_id":null,"session_id":"qa-10k"}`);
      out.push(`{"type":"user","message":{"content":[{"type":"tool_result","tool_use_id":"toolu_${i}","content":"${i}","is_error":${i % 500 === 499}}]},"parent_tool_use_id":null,"session_id":"qa-10k"}`);
    } else {
      out.push(`{"type":"stream_event","event":{"type":"content_block_delta","index":0,"delta":{"type":"text_delta","text":"w${i} "}},"parent_tool_use_id":null,"session_id":"qa-10k"}`);
    }
  }
  out.push('{"type":"result","subtype":"success","is_error":false,"num_turns":1,"session_id":"qa-10k","total_cost_usd":1.2345,"usage":{"input_tokens":1000,"output_tokens":10000}}');
  return out.join('\n') + '\n';
}
const SYNTH_PATH = path.join(tmpdir(), 'qa-synth-10k.jsonl');
writeFileSync(SYNTH_PATH, synth10k());

let attempts: Attempt[] = [];
const seenSpecs: { spec: TurnSpec; resume: string | null; text: string }[] = [];
let skipped = 0;
let release: () => void = () => {};
let held: Promise<void> = Promise.resolve();

const replay: EngineDriver = {
  id: 'claude',
  fingerprint: () => 'replay',
  hasLive: () => false,
  async prewarm() {},
  async runTurn({ chatKey, spec, resume, text, emit }) {
    seenSpecs.push({ spec, resume, text });
    const a = attempts.shift();
    if (!a) throw new Error('replay: no attempt scripted');
    const tr = translate(emit);
    const ls = lines(a.stream);
    for (let i = 0; i < ls.length; i++) {
      if (a.stopBefore === i) await stopChat(chatKey);
      if (a.holdAt === i) await held;
      let m: unknown;
      try {
        m = JSON.parse(ls[i]);
      } catch {
        skipped++;
        continue;
      }
      tr(m as never);
      await Promise.resolve();
    }
    if (a.exit) throw new Error(a.exit);
    return { source: 'cold' };
  },
  async stop() {},
  closeFor() {},
  closeAll() {},
  // The real driver's rule (drivers/claude.ts isCrashError).
  isCrashError(e) {
    const msg = String((e as Error)?.message ?? e);
    return ['3221225477', '3221226505', '3221225725', '-1073741819', '-1073740791', '-1073741571'].some((c) => msg.includes(c)) || msg.includes('session ended');
  },
};
setDriver(replay);

// ------------------------------------------------------------ app.tsx's fold, transcribed

type Msg =
  | { role: 'user'; text: string; at: number }
  | { role: 'assistant'; text: string; at: number; tools: ToolCallItem[]; thinking: boolean }
  | { role: 'notice'; text: string; at: number; level: 'info' | 'error' };

/** src/renderer/app.tsx, the `desk.chat.onEvent` effect (lines ~283–340), for the open chat. */
function fold(ms: Msg[], ev: ChatEvent): Msg[] {
  if (ev.kind === 'init') return ms;
  if (ev.kind === 'done') {
    const last = ms[ms.length - 1];
    const live = last && last.role === 'assistant' && last.at === -1 ? last : null;
    const frozen = live ? [...ms.slice(0, -1), { ...live, at: 1 }] : ms;
    return ev.stopped ? [...frozen, { role: 'notice', text: t('chat.stopped'), at: 1, level: 'info' }] : frozen;
  }
  if (ev.kind === 'error') {
    const text = ev.message === 'busy' ? t('chat.busy') : `${t('chat.error')}: ${ev.message}`;
    return [...ms, { role: 'notice', text, at: 1, level: 'error' }];
  }
  if (ev.kind === 'notice') {
    const m = ev.message.match(/^mcp:([^:]+):(.+)$/);
    const text = m ? t('notice.mcp', { name: m[1], status: m[2] }) : t(`notice.${ev.message}`);
    return [...ms, { role: 'notice', text, at: 1, level: 'info' }];
  }
  const last = ms[ms.length - 1];
  const isLive = Boolean(last && last.role === 'assistant' && last.at === -1);
  const base = isLive && last.role === 'assistant' ? { ...last, tools: [...last.tools] } : { role: 'assistant' as const, text: '', at: -1, tools: [] as ToolCallItem[], thinking: false };
  const rest = isLive ? ms.slice(0, -1) : ms;
  if (ev.kind === 'text') base.text += ev.delta;
  else if (ev.kind === 'thinking') base.thinking = true;
  else if (ev.kind === 'tool') base.tools.push({ id: ev.id, name: ev.name, input: ev.input, ok: null, result: '' });
  else if (ev.kind === 'tool-result') {
    const idx = base.tools.findIndex((x) => x.id === ev.id);
    if (idx >= 0) base.tools[idx] = { ...base.tools[idx], ok: ev.ok, result: ev.text };
  }
  return [...rest, base];
}

